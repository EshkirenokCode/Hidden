const continuity = 'Сначала определи, о чём спрашивает пользователь. В коротких уточнениях, например «а почему?», «приведи пример» или «а второй?», восстанови предмет и ограничения из предыдущих реплик. Если среди них есть исходный вопрос для серии уточнений, сохрани его тему и детали. Отвечай только на текущую реплику. Недавняя расшифровка может содержать посторонние фразы: опирайся прежде всего на вопрос пользователя и предыдущий ответ. Если предмет уточнения действительно неясен, задай один конкретный вопрос. Самостоятельный новый вопрос может менять тему.';

function formatDialogue(request) {
  if (!request.dialogue?.length) return request.conversation || 'Нет';
  return request.dialogue.map(({ question, answer }) => `Пользователь: ${question}\nПомощник: ${answer}`).join('\n\n');
}

module.exports = { continuity, formatDialogue };
